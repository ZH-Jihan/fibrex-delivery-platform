/**
 * Entity and field definitions shared by the API and the web app (phase 2 row 2.4,
 * SPEC 2.10 entity and form builder).
 *
 * Purpose: one definition of
 *   - what a record-type key and a field key look like,
 *   - the field types and the validations each type accepts,
 *   - how a list of fields becomes the JSON Schema stored with a published record type,
 *   - how record data is checked against that schema,
 * so the builder screen, the generated forms and the server agree on every rule.
 *
 * Why the checker is written here and not taken from a JSON Schema library: the schema is
 * always generated by `buildJsonSchema` below, so only the handful of keywords it emits need
 * support; a general library compiles schemas with `new Function`, which the browser's
 * content security policy forbids, and the same code must run in the web app.
 *
 * Depends on: zod, ../lookups (labels). Used by: apps/api kernel/entities, later the custom
 * records API (2.5) and the builder and generated pages (2.6).
 */
import { z } from 'zod';
import { labelsProblem, type LookupLabels } from '../lookups/index.js';

/** Key of a custom record type; also a URL segment (`/records/{key}`) and a permission part. */
export const entityKeyPattern = /^[a-z][a-z0-9_]{0,49}$/;
/** Key of a built-in record type: `<schema>.<table>`, e.g. `party.party`. */
export const systemEntityKeyPattern = /^[a-z][a-z0-9_]{0,49}\.[a-z][a-z0-9_]{0,49}$/;
/** Key of a field: the property name of the value inside the record's data. */
export const fieldKeyPattern = /^[a-z][a-z0-9_]{0,49}$/;

export const FIELD_TYPES = [
  'text',
  'number',
  'decimal',
  'date',
  'dropdown',
  'multi',
  'file',
  'party_ref',
  'entity_ref',
  'boolean',
] as const;
export type FieldType = (typeof FIELD_TYPES)[number];

/**
 * draft: added since the last publish, not yet in use. published: in use. retired: no longer
 * offered on forms, but still in the schema so old records keep their value.
 */
export const FIELD_STATUSES = ['draft', 'published', 'retired'] as const;
export type FieldStatus = (typeof FIELD_STATUSES)[number];

/** Labels per language, as on lookup values: `{ en: 'Inspection date', bn: '...' }`. */
export const labelsSchema = z.record(z.string().min(2).max(10), z.string().trim().max(200));

/** Longest text a text field may hold; also bounds the work of a pattern check. */
export const TEXT_MAX_LENGTH = 4000;
/** Money and quantities are NUMERIC(18,4): at most 14 digits before the point, 4 after. */
export const DECIMAL_MAX_SCALE = 4;
const DECIMAL_TEXT = /^-?\d{1,14}(\.\d{1,4})?$/;
const ISO_DATE = /^\d{4}-\d{2}-\d{2}$/;
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/** True for a calendar date that exists (2026-02-30 does not). */
function isRealDate(text: string): boolean {
  if (!ISO_DATE.test(text)) return false;
  const date = new Date(`${text}T00:00:00Z`);
  return !Number.isNaN(date.getTime()) && date.toISOString().slice(0, 10) === text;
}

/**
 * A decimal string as an integer count of 1/10000ths. BigInt keeps every digit, so limits
 * on money fields are compared exactly (never through a JavaScript float).
 */
function scaledDecimal(text: string): bigint {
  const negative = text.startsWith('-');
  const [whole = '0', fraction = ''] = (negative ? text.slice(1) : text).split('.');
  const value = BigInt(whole + fraction.padEnd(DECIMAL_MAX_SCALE, '0'));
  return negative ? -value : value;
}

/**
 * Why an administrator's text pattern is refused, or null when it is acceptable.
 *
 * The pattern runs on the server against user input, so a pattern that can take exponential
 * time is a denial-of-service risk. Three limits keep the work bounded: the pattern is short,
 * the text it runs on is at most TEXT_MAX_LENGTH, and the two constructions behind runaway
 * matching (a repeated group that itself repeats, and backreferences) are not accepted.
 */
export function textPatternProblem(pattern: string): string | null {
  if (pattern.length > 200) return 'The pattern is too long (200 characters at most).';
  try {
    new RegExp(pattern, 'u');
  } catch {
    return 'This is not a valid pattern.';
  }
  if (/\\[1-9]/.test(pattern) || pattern.includes('\\k<')) {
    return 'Patterns that refer back to an earlier group are not allowed.';
  }
  if (/\([^()]*[+*}][^()]*\)\s*[+*{]/.test(pattern)) {
    return 'A repeated group may not contain another repeat.';
  }
  return null;
}

const isoDate = z.string().refine(isRealDate, { message: 'Use a real date as YYYY-MM-DD' });
const decimalText = z.string().regex(DECIMAL_TEXT, { message: 'Use a number like 1250.50' });
const none = z.strictObject({});

/** The validations each field type accepts. Unknown keys are refused, not ignored. */
const VALIDATION_SCHEMAS: Record<FieldType, z.ZodType<Record<string, unknown>>> = {
  text: z
    .strictObject({
      minLength: z.number().int().min(0).max(TEXT_MAX_LENGTH).optional(),
      maxLength: z.number().int().min(1).max(TEXT_MAX_LENGTH).optional(),
      pattern: z.string().min(1).optional(),
    })
    .superRefine((v, ctx) => {
      if (v.minLength !== undefined && v.maxLength !== undefined && v.minLength > v.maxLength) {
        ctx.addIssue({ code: 'custom', message: 'The shortest length is above the longest.' });
      }
      const problem = v.pattern === undefined ? null : textPatternProblem(v.pattern);
      if (problem !== null) ctx.addIssue({ code: 'custom', message: problem });
    }),
  number: z
    .strictObject({
      min: z.number().int().refine(Number.isSafeInteger).optional(),
      max: z.number().int().refine(Number.isSafeInteger).optional(),
    })
    .refine((v) => v.min === undefined || v.max === undefined || v.min <= v.max, {
      message: 'The lowest value is above the highest.',
    }),
  decimal: z
    .strictObject({
      min: decimalText.optional(),
      max: decimalText.optional(),
      scale: z.number().int().min(0).max(DECIMAL_MAX_SCALE).optional(),
    })
    .refine(
      (v) =>
        v.min === undefined || v.max === undefined || scaledDecimal(v.min) <= scaledDecimal(v.max),
      { message: 'The lowest value is above the highest.' },
    ),
  date: z
    .strictObject({ min: isoDate.optional(), max: isoDate.optional() })
    .refine((v) => v.min === undefined || v.max === undefined || v.min <= v.max, {
      message: 'The earliest date is after the latest.',
    }),
  multi: z
    .strictObject({
      minItems: z.number().int().min(0).max(100).optional(),
      maxItems: z.number().int().min(1).max(100).optional(),
    })
    .refine(
      (v) => v.minItems === undefined || v.maxItems === undefined || v.minItems <= v.maxItems,
      {
        message: 'The fewest choices is above the most.',
      },
    ),
  dropdown: none,
  file: none,
  party_ref: none,
  entity_ref: none,
  boolean: none,
};

export type FieldValidationsResult =
  { ok: true; value: Record<string, unknown> } | { ok: false; message: string };

/** Checks the validations of one field against what its type accepts. */
export function parseFieldValidations(type: FieldType, raw: unknown): FieldValidationsResult {
  const parsed = VALIDATION_SCHEMAS[type].safeParse(raw ?? {});
  if (parsed.success) return { ok: true, value: parsed.data };
  const first = parsed.error.issues[0];
  const where = first === undefined || first.path.length === 0 ? '' : `${first.path.join('.')}: `;
  return { ok: false, message: `${where}${first?.message ?? 'Invalid validations'}` };
}

/** One field as the schema generator needs it. */
export interface FieldSpec {
  key: string;
  label: LookupLabels;
  type: FieldType;
  validations: Record<string, unknown>;
  required: boolean;
  sortOrder: number;
  status: FieldStatus;
  /** Key of the lookup list (dropdown and multi). */
  lookupKey?: string | null;
  /** Key of the record type an `entity_ref` points to. */
  refEntityKey?: string | null;
}

/** One property of the generated schema. `x-` keywords carry what plain JSON Schema cannot. */
export interface JsonSchemaProperty {
  type: 'string' | 'integer' | 'boolean' | 'array';
  title: string;
  'x-field-type': FieldType;
  minLength?: number;
  maxLength?: number;
  pattern?: string;
  minimum?: number;
  maximum?: number;
  format?: 'date' | 'uuid';
  formatMinimum?: string;
  formatMaximum?: string;
  /** Limits of a decimal, kept as strings so no digit is lost. */
  'x-decimal'?: { min?: string; max?: string; scale: number };
  /** The lookup list whose active codes are the allowed values (checked on the server). */
  'x-lookup'?: string;
  /** What a UUID refers to (existence is checked on the server). */
  'x-ref'?: 'party' | 'file' | 'entity';
  'x-ref-entity'?: string;
  'x-retired'?: true;
  items?: { type: 'string' };
  uniqueItems?: true;
  minItems?: number;
  maxItems?: number;
}

export interface RecordJsonSchema {
  $schema: 'https://json-schema.org/draft/2020-12/schema';
  type: 'object';
  additionalProperties: false;
  properties: Record<string, JsonSchemaProperty>;
  required: string[];
}

const asNumber = (value: unknown): number | undefined =>
  typeof value === 'number' ? value : undefined;
const asString = (value: unknown): string | undefined =>
  typeof value === 'string' ? value : undefined;

function propertyFor(field: FieldSpec): JsonSchemaProperty {
  const base = {
    title: field.label.en ?? field.key,
    'x-field-type': field.type,
    ...(field.status === 'retired' ? { 'x-retired': true as const } : {}),
  };
  const v = field.validations;
  switch (field.type) {
    case 'text': {
      const pattern = asString(v.pattern);
      const minLength = asNumber(v.minLength);
      return {
        ...base,
        type: 'string',
        // Always bounded, even when the administrator set no limit.
        maxLength: asNumber(v.maxLength) ?? TEXT_MAX_LENGTH,
        ...(minLength === undefined ? {} : { minLength }),
        ...(pattern === undefined ? {} : { pattern }),
      };
    }
    case 'number': {
      const minimum = asNumber(v.min);
      const maximum = asNumber(v.max);
      return {
        ...base,
        type: 'integer',
        ...(minimum === undefined ? {} : { minimum }),
        ...(maximum === undefined ? {} : { maximum }),
      };
    }
    case 'decimal': {
      // A decimal travels as a string ("1250.50"): JSON numbers are floats and would lose
      // digits of money. The pattern fixes the number of places after the point.
      const scale = asNumber(v.scale) ?? DECIMAL_MAX_SCALE;
      const min = asString(v.min);
      const max = asString(v.max);
      return {
        ...base,
        type: 'string',
        pattern: scale === 0 ? '^-?\\d{1,14}$' : `^-?\\d{1,14}(\\.\\d{1,${String(scale)}})?$`,
        'x-decimal': {
          scale,
          ...(min === undefined ? {} : { min }),
          ...(max === undefined ? {} : { max }),
        },
      };
    }
    case 'date': {
      const min = asString(v.min);
      const max = asString(v.max);
      return {
        ...base,
        type: 'string',
        format: 'date',
        ...(min === undefined ? {} : { formatMinimum: min }),
        ...(max === undefined ? {} : { formatMaximum: max }),
      };
    }
    case 'dropdown':
      return { ...base, type: 'string', 'x-lookup': field.lookupKey ?? '' };
    case 'multi': {
      const minItems = asNumber(v.minItems);
      const maxItems = asNumber(v.maxItems);
      return {
        ...base,
        type: 'array',
        items: { type: 'string' },
        uniqueItems: true,
        'x-lookup': field.lookupKey ?? '',
        ...(minItems === undefined ? {} : { minItems }),
        ...(maxItems === undefined ? {} : { maxItems }),
      };
    }
    case 'file':
      return { ...base, type: 'string', format: 'uuid', 'x-ref': 'file' };
    case 'party_ref':
      return { ...base, type: 'string', format: 'uuid', 'x-ref': 'party' };
    case 'entity_ref':
      return {
        ...base,
        type: 'string',
        format: 'uuid',
        'x-ref': 'entity',
        'x-ref-entity': field.refEntityKey ?? '',
      };
    case 'boolean':
      return { ...base, type: 'boolean' };
  }
}

/**
 * The JSON Schema of a record type's data, from its fields.
 *
 * - Properties are added in form order (sort order, then key). Do not rely on that order
 *   after the schema has been stored: PostgreSQL JSONB reorders keys. The order of a form
 *   comes from the field list, not from the schema.
 * - Unknown properties are refused (`additionalProperties: false`): data can only hold what
 *   the definition names.
 * - A retired field stays as a property so old records still validate, but is never
 *   required: nobody can fill a field that is no longer on the form.
 */
export function buildJsonSchema(fields: readonly FieldSpec[]): RecordJsonSchema {
  const ordered = [...fields].sort(
    (a, b) => a.sortOrder - b.sortOrder || a.key.localeCompare(b.key),
  );
  const properties: Record<string, JsonSchemaProperty> = {};
  for (const field of ordered) properties[field.key] = propertyFor(field);
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    type: 'object',
    additionalProperties: false,
    properties,
    required: ordered.filter((f) => f.required && f.status !== 'retired').map((f) => f.key),
  };
}

export interface RecordIssue {
  /** The field key, or '' for a problem with the data as a whole. */
  path: string;
  message: string;
  code: string;
}

/**
 * "Not filled in": a missing property, null, an empty text or an empty list. Forms send
 * these for a cleared box, so they all mean the same and a required field refuses them all.
 */
export function isAbsent(value: unknown): boolean {
  return (
    value === undefined ||
    value === null ||
    value === '' ||
    (Array.isArray(value) && value.length === 0)
  );
}

/** The data without its not-filled-in properties: the shape to store. */
export function stripAbsent(data: Record<string, unknown>): Record<string, unknown> {
  return Object.fromEntries(Object.entries(data).filter(([, value]) => !isAbsent(value)));
}

function checkString(property: JsonSchemaProperty, value: unknown): [string, string] | null {
  if (typeof value !== 'string') return ['type', 'Text is expected.'];
  if (property.format === 'date') {
    if (!isRealDate(value)) return ['format', 'Use a real date as YYYY-MM-DD.'];
    // ISO dates sort as text, so plain comparison is a date comparison.
    if (property.formatMinimum !== undefined && value < property.formatMinimum) {
      return ['minimum', `Not before ${property.formatMinimum}.`];
    }
    if (property.formatMaximum !== undefined && value > property.formatMaximum) {
      return ['maximum', `Not after ${property.formatMaximum}.`];
    }
    return null;
  }
  if (property.format === 'uuid') {
    return UUID.test(value) ? null : ['format', 'A record id is expected.'];
  }
  // Length in characters as a person counts them (code points), not UTF-16 units.
  const length = Array.from(value).length;
  if (length > (property.maxLength ?? TEXT_MAX_LENGTH)) {
    return ['max_length', `At most ${String(property.maxLength ?? TEXT_MAX_LENGTH)} characters.`];
  }
  if (property.minLength !== undefined && length < property.minLength) {
    return ['min_length', `At least ${String(property.minLength)} characters.`];
  }
  if (property.pattern !== undefined && !new RegExp(property.pattern, 'u').test(value)) {
    return ['pattern', 'This is not in the expected format.'];
  }
  const decimal = property['x-decimal'];
  if (decimal !== undefined) {
    const scaled = scaledDecimal(value);
    if (decimal.min !== undefined && scaled < scaledDecimal(decimal.min)) {
      return ['minimum', `Not below ${decimal.min}.`];
    }
    if (decimal.max !== undefined && scaled > scaledDecimal(decimal.max)) {
      return ['maximum', `Not above ${decimal.max}.`];
    }
  }
  return null;
}

function checkValue(property: JsonSchemaProperty, value: unknown): [string, string] | null {
  switch (property.type) {
    case 'string':
      return checkString(property, value);
    case 'integer':
      if (typeof value !== 'number' || !Number.isSafeInteger(value)) {
        return ['type', 'A whole number is expected.'];
      }
      if (property.minimum !== undefined && value < property.minimum) {
        return ['minimum', `Not below ${String(property.minimum)}.`];
      }
      if (property.maximum !== undefined && value > property.maximum) {
        return ['maximum', `Not above ${String(property.maximum)}.`];
      }
      return null;
    case 'boolean':
      return typeof value === 'boolean' ? null : ['type', 'Yes or no is expected.'];
    case 'array': {
      if (!Array.isArray(value) || value.some((v) => typeof v !== 'string' || v === '')) {
        return ['type', 'A list of choices is expected.'];
      }
      if (new Set(value).size !== value.length) return ['unique', 'A choice is listed twice.'];
      if (property.minItems !== undefined && value.length < property.minItems) {
        return ['min_items', `Choose at least ${String(property.minItems)}.`];
      }
      if (property.maxItems !== undefined && value.length > property.maxItems) {
        return ['max_items', `Choose at most ${String(property.maxItems)}.`];
      }
      return null;
    }
  }
}

/**
 * Checks record data against a schema made by `buildJsonSchema`. Returns every problem
 * found (an empty list means the data is valid) so a form can mark all fields at once.
 *
 * It does not check that a lookup code, a party, a file or a referenced record exists: that
 * needs the database and is done by the server after this passes.
 */
export function validateRecordData(schema: RecordJsonSchema, data: unknown): RecordIssue[] {
  if (typeof data !== 'object' || data === null || Array.isArray(data)) {
    return [{ path: '', code: 'type', message: 'The data must be an object of field values.' }];
  }
  const values = data as Record<string, unknown>;
  const issues: RecordIssue[] = [];
  for (const key of Object.keys(values)) {
    if (!Object.hasOwn(schema.properties, key)) {
      issues.push({ path: key, code: 'unknown_field', message: 'This field does not exist.' });
    }
  }
  for (const [key, property] of Object.entries(schema.properties)) {
    const value = values[key];
    if (isAbsent(value)) {
      if (schema.required.includes(key)) {
        issues.push({ path: key, code: 'required', message: 'This field is required.' });
      }
      continue;
    }
    const problem = checkValue(property, value);
    if (problem !== null) issues.push({ path: key, code: problem[0], message: problem[1] });
  }
  return issues;
}

/** Columns every record list can show besides the type's own fields. */
export const LIST_BUILTIN_COLUMNS = ['number', 'state', 'createdAt', 'updatedAt'] as const;

/** Which columns the generated list shows, in order, and how it is sorted at first. */
export const listConfigSchema = z.strictObject({
  columns: z.array(z.string().min(1).max(60)).max(30).default([]),
  sort: z
    .strictObject({ field: z.string().min(1).max(60), direction: z.enum(['asc', 'desc']) })
    .optional(),
});
export type ListConfig = z.infer<typeof listConfigSchema>;

/** Sections of the generated form or detail page; fields not placed go to a last section. */
export const layoutSchema = z.strictObject({
  sections: z
    .array(
      z.strictObject({
        title: labelsSchema,
        fields: z.array(z.string().regex(fieldKeyPattern)).max(100),
      }),
    )
    .max(30)
    .default([]),
});
export type Layout = z.infer<typeof layoutSchema>;

/**
 * Problems in the list and page layouts given the keys of the fields in use: a column or a
 * placed field that does not exist, a field placed twice, a section without an English title.
 */
export function layoutProblems(
  layouts: { listConfig: ListConfig; formLayout: Layout; detailLayout: Layout },
  fieldKeys: readonly string[],
): RecordIssue[] {
  const issues: RecordIssue[] = [];
  const known = new Set(fieldKeys);
  const builtin: readonly string[] = LIST_BUILTIN_COLUMNS;
  const listed = (name: string) => known.has(name) || builtin.includes(name);
  for (const column of layouts.listConfig.columns) {
    if (!listed(column)) {
      issues.push({
        path: 'listConfig.columns',
        code: 'unknown_field',
        message: `The list shows '${column}', which is not a field.`,
      });
    }
  }
  const sort = layouts.listConfig.sort;
  if (sort !== undefined && !listed(sort.field)) {
    issues.push({
      path: 'listConfig.sort',
      code: 'unknown_field',
      message: `The list is sorted by '${sort.field}', which is not a field.`,
    });
  }
  for (const [path, layout] of [
    ['formLayout', layouts.formLayout],
    ['detailLayout', layouts.detailLayout],
  ] as const) {
    const placed = new Set<string>();
    for (const section of layout.sections) {
      const title = labelsProblem(section.title);
      if (title !== null) issues.push({ path, code: 'english_label_required', message: title });
      for (const key of section.fields) {
        if (!known.has(key)) {
          issues.push({ path, code: 'unknown_field', message: `'${key}' is not a field.` });
        } else if (placed.has(key)) {
          issues.push({ path, code: 'duplicate_field', message: `'${key}' is placed twice.` });
        }
        placed.add(key);
      }
    }
  }
  return issues;
}
